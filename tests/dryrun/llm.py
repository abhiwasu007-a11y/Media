# (throw-away dry-run fixtures feed fakes and dataset dicts into typed APIs)
"""The deterministic SCRIPTED fake LLM of the dry run (PLUMBING TEST - NOT QUALITY).

One instance per agent, with a responder that turns the agent's own rendered request into a
schema-valid structured answer. Nothing is generated by a model; the text is placeholder copy
labelled PLUMBING. Usage is reported with the fake provider name and a synthetic fake price so
the cost ledger, the budget guard and the cost-per-stage report have real rows to work on.
"""

from collections.abc import Callable

from amw_adapters.common import FAKE_PRICE_REF, CallUsage, FakeProvider
from amw_adapters.llm import LlmRequest, LlmResponse, TokenCount
from amw_core.enums import BillingMode, CostOperation

Responder = Callable[[LlmRequest], str]

FAKE_MICROS_PER_CALL = 1_000
"""Synthetic fake price per call (USD 0.001): test configuration, never a real price."""


class _Price:
    micros = FAKE_MICROS_PER_CALL


PRICE = _Price()
"""Mutable fake price (the budget-breach scenario raises it; restored after the run)."""


class ScriptedLlm:
    def __init__(self, responder: Responder, micros_per_call: int | None = None) -> None:
        self._responder = responder
        self._micros = micros_per_call if micros_per_call is not None else PRICE.micros
        self.requests: list[LlmRequest] = []

    @property
    def provider(self) -> str:
        return FakeProvider.LLM.value

    def complete(self, request: LlmRequest, *, idempotency_key: str) -> LlmResponse:
        self.requests.append(request)
        text = self._responder(request)
        chars = sum(len(m.content) for m in request.messages) + len(request.system or "")
        usage = CallUsage(
            provider=FakeProvider.LLM.value,
            operation=CostOperation.LLM_COMPLETION,
            model=request.model,
            billing_mode=BillingMode.STANDARD,
            tokens_in=max(1, chars // 4),
            tokens_out=max(1, len(text) // 4),
            tokens_cached_in=0,
            amount_micros=self._micros,
            currency="USD",
            price_ref=FAKE_PRICE_REF,
            idempotency_key=idempotency_key,
        )
        return LlmResponse(text=text, stop_reason="end_turn", usage=usage)

    def count_tokens(self, request: LlmRequest, *, idempotency_key: str) -> TokenCount:
        raise NotImplementedError("the dry run never counts tokens")
