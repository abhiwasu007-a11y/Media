"""Generate ``packages/amw_core/src/amw_core/enums.py`` from docs/v4/GLOSSARY_AND_IDS.md section 6.

Run ``uv run python -m scripts.gen_enums`` after a glossary change, then ``ruff format``.
``tests/test_enums.py`` fails if the checked-in module and the glossary disagree.
"""

import re
import sys
from pathlib import Path

from tests.docs_tables import glossary_enums

OUT = Path(__file__).resolve().parents[1] / "packages/amw_core/src/amw_core/enums.py"

CLASS_NAMES = {
    "control_command": "ControlCommandKind",
    "ad_spot_duration_s": "AdSpotDurationS",
    "oauth_token_status": "OauthTokenStatus",
}
ALIASES = {"production_type_status": "feature_status", "rule_flag_severity": "rule_severity"}
INT_ENUMS = {"ad_spot_duration_s": "S"}
MEMBER_PREFIX = {"aspect_ratio": "R"}
STRIP = {"rule_pack_key": "rp.", "payload_ref_schema": "amw."}
# ruff's S105 name rule (hardcoded-password-string); enum values are not credentials.
S105 = re.compile(r"(^|_)(pas+wo?r?d|pass(phrase)?|pwd|token|secrete?)($|_)", re.IGNORECASE)

EXTRAS: dict[str, str] = {
    "priority": '''
    @property
    def queue_int(self) -> int:
        """Queue integer of GLOSSARY section 6.5 (0 = most urgent)."""
        return _PRIORITY_QUEUE_INT[self]
''',
    "feature_status": '''
    @property
    def display(self) -> str:
        """Exact display string of GLOSSARY section 6.11 (rule 7)."""
        return _FEATURE_STATUS_DISPLAY[self]
''',
    "approval_state": """
    @property
    def is_final(self) -> bool:
        return self is not ApprovalState.PENDING
""",
    "quality_dimension": '''
    @property
    def max_points(self) -> int:
        """Maximum points of the dimension (GLOSSARY section 6.45; the eight sum to 100)."""
        return _QUALITY_MAX_POINTS[self]
''',
    "ad_spot_duration_s": """
    @property
    def duration_target_ms(self) -> int:
        return int(self) * 1000
""",
    "transition_id": """
    @property
    def entity_kind(self) -> EntityKind:
        return EntityKind.TASK if self.value.startswith("T") else EntityKind.JOB
""",
}

TABLES = """
_PRIORITY_QUEUE_INT: Mapping[Priority, int] = MappingProxyType(
    {p: i for i, p in enumerate(Priority)}
)
_FEATURE_STATUS_DISPLAY: Mapping[FeatureStatus, str] = MappingProxyType(
    {
        FeatureStatus.PLANNED: "Planned",
        FeatureStatus.IN_DEVELOPMENT: "In Development",
        FeatureStatus.IMPLEMENTED: "Implemented",
        FeatureStatus.TESTED: "Tested",
        FeatureStatus.PRODUCTION_READY: "Production Ready",
    }
)
_QUALITY_MAX_POINTS: Mapping[QualityDimension, int] = MappingProxyType(
    {
        QualityDimension.RESEARCH_ACCURACY: 20,
        QualityDimension.STORYTELLING: 15,
        QualityDimension.AUDIENCE_VALUE: 15,
        QualityDimension.VISUAL_QUALITY: 15,
        QualityDimension.AUDIO_QUALITY: 10,
        QualityDimension.EDITING_QUALITY: 10,
        QualityDimension.THUMBNAIL_METADATA: 10,
        QualityDimension.COMPLIANCE: 5,
    }
)
"""


def class_name(name: str) -> str:
    return CLASS_NAMES.get(name) or "".join(p.capitalize() for p in name.split("_"))


def member_name(enum: str, value: str) -> str:
    value = value.removeprefix(STRIP.get(enum, ""))
    name = re.sub(r"[^0-9A-Za-z]+", "_", value).strip("_").upper()
    if enum in INT_ENUMS:
        return INT_ENUMS[enum] + name
    if enum in MEMBER_PREFIX or name[0].isdigit():
        return MEMBER_PREFIX.get(enum, "V") + name
    return name


def render() -> str:
    enums = glossary_enums()
    out = [
        '"""Every status and value enum of docs/v4/GLOSSARY_AND_IDS.md section 6 (master list).',
        "",
        "GENERATED by ``scripts/gen_enums.py`` from the glossary: do not edit by hand.",
        "Values are the exact glossary spellings; DB columns store them as ``text`` with a CHECK",
        "(GLOSSARY section 5).",
        "``GLOSSARY_ENUMS`` maps each glossary enum name to its class.",
        '"""',
        "",
        "from collections.abc import Mapping",
        "from enum import Enum, IntEnum, StrEnum",
        "from types import MappingProxyType",
        "",
    ]
    for name, values in enums.items():
        cls = class_name(name)
        if name in ALIASES:
            out += ["", f"{cls} = {class_name(ALIASES[name])}", f'"""``{name}``: same values."""']
            continue
        base = "IntEnum" if name in INT_ENUMS else "StrEnum"
        out += ["", "", f"class {cls}({base}):", f'    """GLOSSARY ``{name}``."""', ""]
        for value in values:
            member = member_name(name, value)
            literal = value if name in INT_ENUMS else repr(value).replace("'", '"')
            noqa = "  # noqa: S105 - enum value, not a credential" if S105.search(member) else ""
            out.append(f"    {member} = {literal}{noqa}")
        if name in EXTRAS:
            out.append(EXTRAS[name].rstrip("\n"))
    out += [
        "",
        TABLES.rstrip("\n"),
        "",
        "GLOSSARY_ENUMS: Mapping[str, type[Enum]] = MappingProxyType(",
    ]
    out.append("    {")
    out += [f'        "{name}": {class_name(name)},' for name in enums]
    out += ["    }", ")", ""]
    return "\n".join(out)


def main() -> int:
    OUT.write_text(render(), encoding="utf-8")
    sys.stdout.write(f"wrote {OUT}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
