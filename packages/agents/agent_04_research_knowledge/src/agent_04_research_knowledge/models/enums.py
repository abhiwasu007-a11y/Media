class ReliabilityTier(StrEnum):
    A_PRIMARY = "A_PRIMARY"
    B_PUBLISHED = "B_PUBLISHED"
    C_SECONDARY = "C_SECONDARY"
    D_UNVERIFIED = "D_UNVERIFIED"

    @property
    def rank(self) -> int:
        """0 = best (A) ... 3 = worst (D)."""
        return ("A_PRIMARY", "B_PUBLISHED", "C_SECONDARY", "D_UNVERIFIED").index(self.value)


