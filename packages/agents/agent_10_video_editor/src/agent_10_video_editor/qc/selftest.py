"""QC self-test of 18 section 7.11 / blueprint 10 F-43, R-02.

Synthetic fixtures are generated by ``lavfi`` at run time (no stored media, no network). Each
fixture's expected verdict is asserted: a clean file passes every sourced check; a file with true
peak above -1 dBTP, a black segment, a frozen segment, a silence run, a 1-frame A/V start offset,
an SRT overlap, an encode with the delivery settings, a Baseline encode at the wrong frame
rate and an SSIM measurement (ADR-014) each produce their asserted verdict. The test re-runs
whenever the FFmpeg build ID changes; the record is stored and read by readiness.
"""

from dataclasses import dataclass
from pathlib import Path

from agent_10_video_editor.ffmpeg import ArgvBuilder, FfmpegRunner, RunLimits
from agent_10_video_editor.media import run_checked
from agent_10_video_editor.probe import (
    BlackdetectParser,
    Ebur128Parser,
    FreezedetectParser,
    ProbeParser,
    SilencedetectParser,
    SsimParser,
    X264SeiParser,
)
from agent_10_video_editor.qc.checks import (
    qc_audio_silence_mix,
    qc_audio_true_peak,
    qc_subtitles_format,
    qc_sync_av_container,
    qc_video_black_frames,
    qc_video_encoder_settings,
    qc_video_freeze,
    qc_video_quality_metric,
)
from agent_10_video_editor.subtitles import Cue, SrtParser, SrtValidator, SrtWriter

_DURATION_S = 6


@dataclass(frozen=True, slots=True)
class SelfTestCase:
    name: str
    expected: str
    actual: str

    @property
    def ok(self) -> bool:
        return self.expected == self.actual


@dataclass(frozen=True, slots=True)
class SelfTestRecord:
    ffmpeg_build_id: str
    cases: tuple[SelfTestCase, ...]

    @property
    def passed(self) -> bool:
        return all(case.ok for case in self.cases)


def _gen(
    builder: ArgvBuilder,
    name: str,
    video: str,
    audio: str,
    *,
    extra: tuple[str, ...] = (),
    audio_offset_s: str | None = None,
) -> list[str]:
    offset = ["-itsoffset", audio_offset_s] if audio_offset_s else []
    return [
        builder.ffmpeg_bin, "-hide_banner", "-nostdin", "-y", "-loglevel", "error",
        "-f", "lavfi", "-i", video, *offset, "-f", "lavfi", "-i", audio,
        "-t", str(_DURATION_S), "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac",
        "-ar", "48000", "-ac", "2", *extra, name,
    ]  # fmt: skip


class QcSelfTest:
    """F-43: ``run(runner)`` returns the record; nothing is written outside ``work``."""

    @staticmethod
    def run(
        runner: FfmpegRunner, builder: ArgvBuilder, work: Path, build_id: str
    ) -> SelfTestRecord:
        limits = RunLimits()
        busy = "testsrc2=size=320x180:rate=25,noise=alls=40:allf=t"
        tone = "sine=frequency=440:sample_rate=48000"
        cases: list[SelfTestCase] = []

        def make(
            name: str, video: str, audio: str, *extra: str, audio_offset_s: str | None = None
        ) -> str:
            argv = _gen(builder, name, video, audio, extra=extra, audio_offset_s=audio_offset_s)
            run_checked(runner, argv, cwd=work, limits=limits)
            return name

        def audio_peak(name: str) -> float:
            res = run_checked(runner, builder.ebur128(name), cwd=work, limits=limits)
            return Ebur128Parser.parse(res.stderr)["true_peak_dbtp"]

        # 1. clean: quiet tone, busy video, no black/freeze/silence
        clean = make("clean.mp4", busy, f"{tone},volume=-20dB")
        peak = audio_peak(clean)
        cases.append(
            _case(
                "clean.true_peak",
                "PASS",
                qc_audio_true_peak(true_peak_dbtp=peak, ceiling_dbtp=-1.0),
            )
        )
        cases.append(_case("clean.black", "PASS", _black(runner, builder, work, clean)))
        cases.append(_case("clean.freeze", "PASS", _freeze(runner, builder, work, clean)))
        cases.append(_case("clean.silence", "PASS", _silence(runner, builder, work, clean)))
        # 2. true peak above -1 dBTP (both channels at 0.98 of full scale)
        hot = make(
            "hot.mp4", busy, "aevalsrc=exprs=0.98*sin(2*PI*440*t)|0.98*sin(2*PI*440*t):s=48000"
        )
        cases.append(
            _case(
                "hot.true_peak",
                "FAIL",
                qc_audio_true_peak(true_peak_dbtp=audio_peak(hot), ceiling_dbtp=-1.0),
            )
        )
        # 3. black segment
        black = make(
            "black.mp4",
            f"{busy},drawbox=enable='between(t,1,4)':t=fill:c=black",
            f"{tone},volume=-20dB",
        )
        cases.append(_case("black.black", "FAIL", _black(runner, builder, work, black)))
        # 4. frozen segment
        frozen = make("frozen.mp4", "color=c=blue:size=320x180:rate=25", f"{tone},volume=-20dB")
        cases.append(_case("frozen.freeze", "FAIL", _freeze(runner, builder, work, frozen)))
        # 5. silence run
        silent = make(
            "silent.mp4", busy, f"{tone},volume=-20dB,volume=enable='between(t,1,5)':volume=0"
        )
        cases.append(_case("silent.silence", "FAIL", _silence(runner, builder, work, silent)))
        # 6. one-frame A/V start offset (audio starts one frame, 40 ms at 25 fps, late)
        offset = make("offset.mp4", busy, f"{tone},volume=-20dB", audio_offset_s="0.040")
        res = run_checked(runner, builder.probe_full(offset), cwd=work, limits=limits)
        probe = ProbeParser.parse(res.stdout)
        v_start = probe.video.start_time or "0"
        a_start = (probe.audio.start_time if probe.audio else "0") or "0"
        sync = qc_sync_av_container(
            start_video_s=v_start,
            start_audio_s=a_start,
            duration_video_s="1",
            duration_audio_s="1",
            frame_ms=40,
            tol_start_ms=0,
            tol_dur_ms=1000,
        )
        cases.append(_case("offset.av_start", "FAIL", sync))
        # 7. SRT overlap
        overlap = SrtWriter.write([Cue(1, 0, 1500, "a"), Cue(2, 1000, 2000, "b")])
        errors = SrtValidator.validate(SrtParser.parse(overlap), 5000)
        cases.append(_case("srt.overlap", "FAIL", qc_subtitles_format(errors=errors)))
        # 8. encoder settings (ADR-014): the delivery settings pass; a Baseline encode at the
        # wrong frame rate fails; the SSIM against a lossless reference is measured (report only)
        moving = "testsrc2=size=320x180:rate=30"
        x264 = "keyint=15:min-keyint=15:scenecut=0:open-gop=0:bframes=2:cabac=1:threads=1"
        good = make(
            "settings.mp4", moving, f"{tone},volume=-20dB",
            "-r", "30", "-preset", "faster", "-profile:v", "high", "-b:v", "8000000",
            "-bf", "2", "-x264-params", x264,
        )  # fmt: skip
        bad = make(
            "baseline.mp4", moving, f"{tone},volume=-20dB",
            "-r", "25", "-preset", "faster", "-profile:v", "baseline", "-b:v", "8000000",
        )  # fmt: skip
        cases.append(
            _case("settings.encoder_settings", "PASS", _settings(runner, builder, work, good))
        )
        cases.append(
            _case("baseline.encoder_settings", "FAIL", _settings(runner, builder, work, bad))
        )
        ref = [
            builder.ffmpeg_bin, "-hide_banner", "-nostdin", "-y", "-loglevel", "error",
            "-f", "lavfi", "-i", moving, "-t", str(_DURATION_S), "-r", "30",
            "-c:v", "ffv1", "-level", "3", "-g", "1", "-pix_fmt", "yuv420p", "-f", "matroska",
            "settings_ref.mkv",
        ]  # fmt: skip
        run_checked(runner, ref, cwd=work, limits=limits)
        res = run_checked(runner, builder.ssim(good, "settings_ref.mkv"), cwd=work, limits=limits)
        cases.append(
            _case(
                "settings.quality_metric",
                "WARN",
                qc_video_quality_metric(
                    ssim_all=SsimParser.parse(res.stderr),
                    frames_measured=30 * _DURATION_S,
                    frames_total=30 * _DURATION_S,
                    min_ssim=None,
                    vmaf_status="LIBVMAF_NOT_IN_BUILD",
                ),
            )
        )
        return SelfTestRecord(build_id, tuple(cases))


def _case(name: str, expected: str, result: object) -> SelfTestCase:
    verdict = getattr(result, "verdict", None)
    return SelfTestCase(name, expected, str(verdict))


def _settings(runner: FfmpegRunner, b: ArgvBuilder, work: Path, name: str) -> object:
    res = run_checked(runner, b.probe_full(name), cwd=work, limits=RunLimits())
    video = ProbeParser.parse(res.stdout).video
    return qc_video_encoder_settings(
        codec_name=video.codec_name,
        profile=video.profile,
        pix_fmt=video.pix_fmt,
        field_order=video.field_order,
        r_frame_rate=video.r_frame_rate,
        level=video.level,
        sei=X264SeiParser.scan_file(work / name),
        fps_num=30,
        fps_den=1,
        gop_frames=15,
        bframes=2,
        cabac=True,
        target_bps=8_000_000,
        maxrate_bps=None,
        bufsize_bps=None,
    )


def _black(runner: FfmpegRunner, b: ArgvBuilder, work: Path, name: str) -> object:
    res = run_checked(
        runner, b.blackdetect(name, "1", "0.98", "0.10"), cwd=work, limits=RunLimits()
    )
    return qc_video_black_frames(
        detections_ms=BlackdetectParser.parse(res.stderr),
        deliberate_black_ms=[],
        total_ms=_DURATION_S * 1000,
        calibrated=True,
    )


def _freeze(runner: FfmpegRunner, b: ArgvBuilder, work: Path, name: str) -> object:
    res = run_checked(runner, b.freezedetect(name, -60, "1"), cwd=work, limits=RunLimits())
    return qc_video_freeze(
        detections_ms=FreezedetectParser.parse(res.stderr, _DURATION_S * 1000),
        deliberate_hold_ms=[],
        total_ms=_DURATION_S * 1000,
        calibrated=True,
    )


def _silence(runner: FfmpegRunner, b: ArgvBuilder, work: Path, name: str) -> object:
    res = run_checked(runner, b.silencedetect(name, -50, "1"), cwd=work, limits=RunLimits())
    return qc_audio_silence_mix(
        runs_ms=SilencedetectParser.parse(res.stderr, _DURATION_S * 1000),
        deliberate_pause_ms=[],
        total_ms=_DURATION_S * 1000,
        max_ms=1000,
    )
